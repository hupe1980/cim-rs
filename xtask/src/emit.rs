fn primitive(p: Primitive) -> &'static str {
    match p {
        Primitive::String => "Primitive::String",
        Primitive::Integer => "Primitive::Integer",
        Primitive::Float => "Primitive::Float",
        Primitive::Decimal => "Primitive::Decimal",
        Primitive::Boolean => "Primitive::Boolean",
        Primitive::Date => "Primitive::Date",
        Primitive::DateTime => "Primitive::DateTime",
        Primitive::MonthDay => "Primitive::MonthDay",
        Primitive::Time => "Primitive::Time",
        Primitive::Duration => "Primitive::Duration",
        Primitive::Uri => "Primitive::Uri",
    }
}

fn mult(m: Multiplicity) -> String {
    match m {
        Multiplicity::Optional => "Mult::Optional".to_owned(),
        Multiplicity::Required => "Mult::Required".to_owned(),
        Multiplicity::Many => "Mult::Many".to_owned(),
        Multiplicity::ManyRequired => "Mult::ManyRequired".to_owned(),
        Multiplicity::Bounded { min, max } => format!("Mult::Bounded {{ min: {min}, max: {max} }}"),
    }
}

fn quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn opt_quote(s: Option<&str>) -> String {
    match s {
        Some(v) => format!("Some({})", quote(v)),
        None => "None".to_owned(),
    }
}

/// Render a schema comment as a rustdoc block at the given indent level.
fn doc_comment(comment: Option<&str>, indent: usize) -> String {
    let Some(c) = comment.filter(|c| !c.is_empty()) else {
        return String::new();
    };
    let pad = "    ".repeat(indent);
    let mut out = String::new();
    // Keep documentation bounded; the standard's longest comments run to pages.
    for line in c.lines().take(24) {
        out.push_str(&pad);
        out.push_str("/// ");
        out.push_str(&escape_doc(line));
        out.push('\n');
    }
    out
}

/// Neutralize constructs in the standard's own prose that rustdoc would reject.
///
/// Class documentation is copied verbatim from IEC 61970-301, which uses brackets and
/// bare URLs freely. Brackets would be parsed as intra-doc links and bare URLs trip
/// `rustdoc::bare_urls`, so both are made inert.
fn escape_doc(s: &str) -> String {
    let cleaned = s.replace('\r', "").replace('[', "\\[").replace(']', "\\]");
    autolink(cleaned.trim())
}

/// Wrap bare `http(s)://` URLs in angle brackets so rustdoc renders them as links.
fn autolink(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(start) = find_url(rest) {
        out.push_str(&rest[..start]);
        let tail = &rest[start..];
        // A URL runs to whitespace; trailing sentence punctuation is not part of it.
        let mut end = tail.find(char::is_whitespace).unwrap_or(tail.len());
        while end > 0 && matches!(tail.as_bytes()[end - 1], b'.' | b',' | b';' | b':' | b')') {
            end -= 1;
        }
        out.push('<');
        out.push_str(&tail[..end]);
        out.push('>');
        rest = &tail[end..];
    }
    out.push_str(rest);
    out
}

fn find_url(s: &str) -> Option<usize> {
    let http = s.find("http://");
    let https = s.find("https://");
    match (http, https) {
        (Some(a), Some(b)) => Some(a.min(b)),
        (Some(a), None) => Some(a),
        (None, Some(b)) => Some(b),
        (None, None) => None,
    }
}

/// Rust keywords that cannot be used as bare identifiers.
const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn",
    "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
    "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "union",
    "unsafe", "use", "where", "while", "async", "await", "box", "final", "macro", "override",
    "priv", "try", "typeof", "unsized", "virtual", "yield", "abstract", "become", "do",
];

fn sanitize(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
        } else {
            out.push('_');
        }
    }
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    if out.is_empty() {
        out.push('_');
    }
    out
}

/// Constant name mirroring the CIM identifier exactly.
///
/// CIM names are the stable, documented surface of the standard, and transforming them
/// loses information: `UnitMultiplier.M` (mega) and `UnitMultiplier.m` (milli) both
/// upper-case to `M`. Keeping the original spelling makes every generated identifier
/// unambiguous and lets a reader of IEC 61970-301 find it without guessing a mapping.
fn rust_const(s: &str) -> String {
    let out = sanitize(s);
    if KEYWORDS.contains(&out.as_str()) {
        format!("{out}_")
    } else {
        out
    }
}

/// snake_case module name.
fn rust_module(s: &str) -> String {
    let out = snake_case(&sanitize(s));
    if KEYWORDS.contains(&out.as_str()) {
        format!("{out}_")
    } else {
        out
    }
}

/// snake_case method name for the public view API, where Rust idiom applies.
fn rust_method(s: &str) -> String {
    rust_module(s)
}

/// Convert a CIM camel/Pascal identifier to snake_case.
///
/// Runs of capitals are kept together, so `mRID` becomes `m_rid` and `ACLineSegment`
/// becomes `ac_line_segment` rather than `a_c_line_segment`.
fn snake_case(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::with_capacity(s.len() + 4);
    for (i, &c) in chars.iter().enumerate() {
        if c == '_' {
            if !out.ends_with('_') && !out.is_empty() {
                out.push('_');
            }
            continue;
        }
        if c.is_ascii_uppercase() && i > 0 {
            let prev = chars[i - 1];
            let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            // Boundary after a lowercase/digit, or before the tail of an acronym.
            let boundary = prev.is_ascii_lowercase()
                || prev.is_ascii_digit()
                || (prev.is_ascii_uppercase() && next_lower);
            if boundary && !out.ends_with('_') {
                out.push('_');
            }
        }
        out.push(c.to_ascii_lowercase());
    }
    while out.contains("__") {
        out = out.replace("__", "_");
    }
    out
}

/// PascalCase type name; CIM class names are already PascalCase.
fn rust_type(s: &str) -> String {
    let out = sanitize(s);
    if KEYWORDS.contains(&out.as_str()) {
        format!("{out}_")
    } else {
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn constants_mirror_the_standards_own_spelling() {
        // Transforming CIM names loses information: `UnitMultiplier.M` (mega) and
        // `UnitMultiplier.m` (milli) both upper-case to `M`.
        assert_eq!(rust_const("ACLineSegment"), "ACLineSegment");
        assert_eq!(rust_const("mRID"), "mRID");
        assert_eq!(rust_const("nominalVoltage"), "nominalVoltage");
        assert_ne!(rust_const("M"), rust_const("m"));
        assert_eq!(rust_const("M"), "M");
        assert_eq!(rust_const("m"), "m");
    }

    #[test]
    fn method_names_are_snake_case_with_acronyms_kept_together() {
        assert_eq!(rust_method("ACLineSegment"), "ac_line_segment");
        assert_eq!(rust_method("mRID"), "m_rid");
        assert_eq!(rust_method("nominalVoltage"), "nominal_voltage");
        assert_eq!(rust_method("r"), "r");
        assert_eq!(rust_method("b0ch"), "b0ch");
        assert_eq!(rust_method("BaseVoltage"), "base_voltage");
        // Reserved words are escaped so `SynchronousMachine.type` stays usable.
        assert_eq!(rust_method("type"), "type_");
    }

    #[test]
    fn keywords_and_digits_are_escaped() {
        assert_eq!(rust_module("type"), "type_");
        assert_eq!(rust_method("ref"), "ref_");
        assert!(sanitize("3phase").starts_with('_'));
    }

    #[test]
    fn doc_escaping_neutralizes_brackets() {
        assert_eq!(escape_doc("see [IEC]"), "see \\[IEC\\]");
    }
}
