fn emit_tables(schema: &Schema) -> Result<String> {
    let ns_index: BTreeMap<&str, usize> = schema
        .namespaces
        .keys()
        .enumerate()
        .map(|(i, ns)| (ns.as_str(), i))
        .collect();
    let class_index: BTreeMap<&Name, usize> = schema
        .classes
        .keys()
        .enumerate()
        .map(|(i, n)| (n, i))
        .collect();
    let enum_index: BTreeMap<&Name, usize> = schema
        .enums
        .keys()
        .enumerate()
        .map(|(i, n)| (n, i))
        .collect();
    let dt_index: BTreeMap<&Name, usize> = schema
        .datatypes
        .keys()
        .enumerate()
        .map(|(i, n)| (n, i))
        .collect();

    // Attributes get a single flat table; every class refers to them by index.
    let mut attr_rows: Vec<(&Name, &Class, &crate::ir::Attribute)> = Vec::new();
    for class in schema.classes.values() {
        for a in &class.attributes {
            attr_rows.push((&a.name, class, a));
        }
    }
    attr_rows.sort_by(|a, b| a.0.cmp(b.0));
    let attr_index: BTreeMap<&Name, usize> = attr_rows
        .iter()
        .enumerate()
        .map(|(i, (n, _, _))| (*n, i))
        .collect();

    let mut enum_value_rows: Vec<(&Name, usize, &crate::ir::EnumValue)> = Vec::new();
    for (ei, e) in schema.enums.values().enumerate() {
        for v in &e.values {
            enum_value_rows.push((&v.name, ei, v));
        }
    }
    enum_value_rows.sort_by(|a, b| a.0.cmp(b.0));
    let enum_value_index: BTreeMap<&Name, usize> = enum_value_rows
        .iter()
        .enumerate()
        .map(|(i, (n, _, _))| (*n, i))
        .collect();

    if attr_rows.len() > u16::MAX as usize || schema.classes.len() > u16::MAX as usize {
        bail!("schema exceeds the u16 id space");
    }

    let mut s = String::with_capacity(4 << 20);
    s.push_str(HEADER);
    s.push_str(
        "
#![allow(clippy::all)]

use crate::schema::*;

",
    );

    // Namespaces.
    writeln!(s, "static NAMESPACES: &[NamespaceDef] = &[").unwrap();
    for (ns, prefix) in &schema.namespaces {
        writeln!(
            s,
            "    NamespaceDef {{ iri: {}, prefix: {} }},",
            quote(ns),
            quote(prefix)
        )
        .unwrap();
    }
    s.push_str("];\n\n");

    // Profiles.
    writeln!(s, "static PROFILES: &[ProfileDef] = &[").unwrap();
    for p in &schema.profiles {
        writeln!(
            s,
            "    ProfileDef {{ keyword: {}, version_iri: {}, title: {} }},",
            quote(&p.keyword),
            quote(&p.version_iri),
            quote(&p.title)
        )
        .unwrap();
    }
    s.push_str("];\n\n");

    // Per-class attribute id slices.
    for (ci, class) in schema.classes.values().enumerate() {
        let own: Vec<String> = class
            .attributes
            .iter()
            .map(|a| format!("AttrId({})", attr_index[&a.name]))
            .collect();
        writeln!(s, "static OWN_{ci}: &[AttrId] = &[{}];", own.join(", ")).unwrap();

        let all: Vec<String> = schema
            .all_attributes(&class.name)
            .iter()
            .map(|(_, a)| format!("AttrId({})", attr_index[&a.name]))
            .collect();
        writeln!(s, "static ALL_{ci}: &[AttrId] = &[{}];", all.join(", ")).unwrap();

        let anc: Vec<String> = schema
            .ancestors(&class.name)
            .iter()
            .map(|c| format!("ClassId({})", class_index[&c.name]))
            .collect();
        writeln!(s, "static ANC_{ci}: &[ClassId] = &[{}];", anc.join(", ")).unwrap();
    }
    s.push('\n');

    // Classes.
    writeln!(s, "static CLASSES: &[ClassDef] = &[").unwrap();
    for (ci, class) in schema.classes.values().enumerate() {
        let parent = match &class.parent {
            Some(p) => format!("Some(ClassId({}))", class_index[p]),
            None => "None".to_owned(),
        };
        writeln!(
            s,
            "    ClassDef {{ name: {}, ns: NsId({}), parent: {parent}, concrete: {}, \
             profiles: {}, deprecated: {}, own_attrs: OWN_{ci}, all_attrs: ALL_{ci}, \
             ancestors: ANC_{ci}, doc: {} }},",
            quote(&class.name.local),
            ns_index[class.name.ns.as_str()],
            class.concrete,
            class.profiles,
            class.deprecated,
            quote(class.comment.as_deref().unwrap_or(""))
        )
        .unwrap();
    }
    s.push_str("];\n\n");

    // Attributes.
    writeln!(s, "static ATTRIBUTES: &[AttrDef] = &[").unwrap();
    for (name, owner, a) in &attr_rows {
        let kind = match &a.kind {
            AttrKind::Primitive(p) => format!("AttrKind::Primitive({})", primitive(*p)),
            AttrKind::Datatype(d) => match dt_index.get(d) {
                Some(i) => format!("AttrKind::Datatype(DatatypeId({i}))"),
                None => "AttrKind::Primitive(Primitive::String)".to_owned(),
            },
            AttrKind::Enumeration(e) => match enum_index.get(e) {
                Some(i) => format!("AttrKind::Enumeration(EnumId({i}))"),
                None => "AttrKind::Primitive(Primitive::String)".to_owned(),
            },
            AttrKind::Association {
                target, inverse, ..
            } => {
                let Some(t) = class_index.get(target) else {
                    // Target outside the vintage: degrade to an opaque reference rather
                    // than dropping the attribute.
                    continue;
                };
                let inv = inverse
                    .as_ref()
                    .and_then(|i| attr_index.get(i))
                    .map(|i| format!("Some(AttrId({i}))"))
                    .unwrap_or_else(|| "None".to_owned());
                format!("AttrKind::Association {{ target: ClassId({t}), inverse: {inv} }}")
            }
        };
        // Plain attributes are always serialized where they exist; only associations
        // distinguish a used from a derived side.
        let used_in = match &a.kind {
            AttrKind::Association { used_in, .. } => *used_in,
            _ => a.profiles,
        };
        let fixed = match &a.fixed {
            Some(f) => format!("Some({})", quote(f)),
            None => "None".to_owned(),
        };
        writeln!(
            s,
            "    AttrDef {{ name: {}, label: {}, ns: NsId({}), owner: ClassId({}), \
             kind: {kind}, mult: {}, profiles: {}, used_in: {used_in}, deprecated: {}, \
             fixed: {fixed}, doc: {} }},",
            quote(&name.local),
            quote(&a.label),
            ns_index[name.ns.as_str()],
            class_index[&owner.name],
            mult(a.multiplicity),
            a.profiles,
            a.deprecated,
            quote(a.comment.as_deref().unwrap_or(""))
        )
        .unwrap();
    }
    s.push_str("];\n\n");

    // Enumerations.
    for (ei, e) in schema.enums.values().enumerate() {
        let vals: Vec<String> = e
            .values
            .iter()
            .map(|v| format!("EnumValueId({})", enum_value_index[&v.name]))
            .collect();
        writeln!(
            s,
            "static ENUM_VALS_{ei}: &[EnumValueId] = &[{}];",
            vals.join(", ")
        )
        .unwrap();
    }
    s.push('\n');

    writeln!(s, "static ENUMS: &[EnumDef] = &[").unwrap();
    for (ei, e) in schema.enums.values().enumerate() {
        writeln!(
            s,
            "    EnumDef {{ name: {}, ns: NsId({}), profiles: {}, values: ENUM_VALS_{ei}, doc: {} }},",
            quote(&e.name.local),
            ns_index[e.name.ns.as_str()],
            e.profiles,
            quote(e.comment.as_deref().unwrap_or(""))
        )
        .unwrap();
    }
    s.push_str("];\n\n");

    writeln!(s, "static ENUM_VALUES: &[EnumValueDef] = &[").unwrap();
    for (name, owner, v) in &enum_value_rows {
        writeln!(
            s,
            "    EnumValueDef {{ name: {}, label: {}, ns: NsId({}), owner: EnumId({owner}), doc: {} }},",
            quote(&name.local),
            quote(&v.label),
            ns_index[name.ns.as_str()],
            quote(v.comment.as_deref().unwrap_or(""))
        )
        .unwrap();
    }
    s.push_str("];\n\n");

    // Datatypes.
    writeln!(s, "static DATATYPES: &[DatatypeDef] = &[").unwrap();
    for d in schema.datatypes.values() {
        writeln!(
            s,
            "    DatatypeDef {{ name: {}, ns: NsId({}), value: {}, unit: {}, multiplier: {}, doc: {} }},",
            quote(&d.name.local),
            ns_index[d.name.ns.as_str()],
            primitive(d.value),
            opt_quote(d.unit.as_deref()),
            opt_quote(d.multiplier.as_deref()),
            quote(d.comment.as_deref().unwrap_or(""))
        )
        .unwrap();
    }
    s.push_str("];\n\n");

    // Lookup indexes, sorted by (namespace index, name) to allow binary search.
    let mut cidx: Vec<(usize, &str, usize)> = schema
        .classes
        .keys()
        .enumerate()
        .map(|(i, n)| (ns_index[n.ns.as_str()], n.local.as_str(), i))
        .collect();
    cidx.sort_by(|a, b| a.0.cmp(&b.0).then(a.1.cmp(b.1)));
    writeln!(s, "static CLASS_INDEX: &[(u16, &str, ClassId)] = &[").unwrap();
    for (ns, name, id) in cidx {
        writeln!(s, "    ({ns}, {}, ClassId({id})),", quote(name)).unwrap();
    }
    s.push_str("];\n\n");

    let mut aidx: Vec<(usize, &str, usize)> = attr_rows
        .iter()
        .enumerate()
        .map(|(i, (n, _, _))| (ns_index[n.ns.as_str()], n.local.as_str(), i))
        .collect();
    aidx.sort_by(|a, b| a.0.cmp(&b.0).then(a.1.cmp(b.1)));
    writeln!(s, "static ATTR_INDEX: &[(u16, &str, AttrId)] = &[").unwrap();
    for (ns, name, id) in aidx {
        writeln!(s, "    ({ns}, {}, AttrId({id})),", quote(name)).unwrap();
    }
    s.push_str("];\n\n");

    let mut eidx: Vec<(usize, &str, usize)> = enum_value_rows
        .iter()
        .enumerate()
        .map(|(i, (n, _, _))| (ns_index[n.ns.as_str()], n.local.as_str(), i))
        .collect();
    eidx.sort_by(|a, b| a.0.cmp(&b.0).then(a.1.cmp(b.1)));
    writeln!(
        s,
        "static ENUM_VALUE_INDEX: &[(u16, &str, EnumValueId)] = &["
    )
    .unwrap();
    for (ns, name, id) in eidx {
        writeln!(s, "    ({ns}, {}, EnumValueId({id})),", quote(name)).unwrap();
    }
    s.push_str("];\n\n");

    writeln!(
        s,
        "static SCHEMA_DATA: Schema = Schema {{
    vintage: {},
    namespaces: NAMESPACES,
    profiles: PROFILES,
    classes: CLASSES,
    attributes: ATTRIBUTES,
    enums: ENUMS,
    enum_values: ENUM_VALUES,
    datatypes: DATATYPES,
    class_index: CLASS_INDEX,
    attr_index: ATTR_INDEX,
    enum_value_index: ENUM_VALUE_INDEX,
}};

/// The {} schema.
pub static SCHEMA: &Schema = &SCHEMA_DATA;",
        quote(&schema.vintage),
        schema.vintage
    )
    .unwrap();

    Ok(s)
}

