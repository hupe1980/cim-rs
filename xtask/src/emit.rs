fn emit_views(schema: &Schema) -> String {
    let mut s = String::with_capacity(2 << 20);
    s.push_str(HEADER);
    s.push_str(
        "
//! Typed views over stored objects.
//!
//! A view is a zero-cost wrapper around an [`Object`](crate::object::Object) that gives
//! schema-checked, typed access to the attributes of one class. Views borrow rather than
//! own, so obtaining one never copies model data.

#![allow(clippy::all, non_upper_case_globals, non_snake_case)]

use crate::dataset::Dataset;
use crate::mrid::Mrid;
use crate::object::Object;
use crate::schema::{ClassId, EnumValueId};
use crate::view::{TypedView, TypedRef};

use super::names::{attributes as attrs, classes};

",
    );

    for class in schema.classes.values() {
        let ident = rust_type(&class.name.local);
        let class_const = rust_const(&class.name.local);
        let doc = doc_comment(class.comment.as_deref(), 0);
        writeln!(
            s,
            "{doc}#[derive(Clone, Copy, Debug)]\npub struct {ident}<'a>(pub &'a Object);\n"
        )
        .unwrap();

        writeln!(
            s,
            "impl<'a> TypedView<'a> for {ident}<'a> {{\n    const CLASS: ClassId = classes::{class_const};\n    #[inline]\n    fn from_object(o: &'a Object) -> Self {{ {ident}(o) }}\n    #[inline]\n    fn object(&self) -> &'a Object {{ self.0 }}\n}}\n"
        )
        .unwrap();

        writeln!(s, "impl<'a> {ident}<'a> {{").unwrap();
        writeln!(
            s,
            "    /// The object's master resource identifier.\n    #[inline]\n    pub fn mrid(&self) -> &'a Mrid {{ self.0.mrid() }}\n"
        )
        .unwrap();

        // Assign method names most-derived first, so a subclass attribute keeps the
        // plain name and a shadowed inherited one is qualified by its declaring class.
        // `mrid` is reserved for the identifier accessor emitted above.
        let mut taken: BTreeMap<String, ()> = BTreeMap::new();
        taken.insert("mrid".to_owned(), ());
        let attrs: Vec<_> = schema.all_attributes(&class.name);
        let mut methods: Vec<String> = vec![String::new(); attrs.len()];
        for (i, (owner, attr)) in attrs.iter().enumerate().rev() {
            let label = attr.name.local.rsplit('.').next().unwrap_or("");
            let mut method = rust_method(label);
            if taken.contains_key(&method) {
                method = format!("{}_{}", rust_module(&owner.name.local), rust_method(label));
            }
            // Still colliding (two classes, same names): fall back to a numbered form.
            if taken.contains_key(&method) {
                method = format!("{method}_{i}");
            }
            taken.insert(method.clone(), ());
            methods[i] = method;
        }

        for (i, (owner, attr)) in attrs.iter().enumerate() {
            let owner_mod = rust_module(&owner.name.local);
            let label = attr.name.local.rsplit('.').next().unwrap_or("");
            let const_name = rust_const(label);
            let path = format!("attrs::{owner_mod}::{const_name}");
            let doc = doc_comment(attr.comment.as_deref(), 1);
            emit_accessor(&mut s, schema, attr, &path, &methods[i], &doc);
        }
        s.push_str("}\n\n");
    }

    s
}

fn emit_accessor(
    s: &mut String,
    schema: &Schema,
    attr: &crate::ir::Attribute,
    path: &str,
    method: &str,
    doc: &str,
) {
    let many = attr.multiplicity.is_many();
    match &attr.kind {
        AttrKind::Primitive(p) => {
            let (ty, conv) = primitive_accessor(*p);
            if many {
                writeln!(
                    s,
                    "{doc}    pub fn {method}(&self) -> impl Iterator<Item = {ty}> + '_ {{\n        self.0.get_all({path}).iter().filter_map(|s| s.value.{conv})\n    }}\n"
                )
                .unwrap();
            } else {
                writeln!(
                    s,
                    "{doc}    #[inline]\n    pub fn {method}(&self) -> Option<{ty}> {{\n        self.0.get({path}).and_then(|v| v.{conv})\n    }}\n"
                )
                .unwrap();
            }
        }
        AttrKind::Datatype(d) => {
            let prim = schema
                .datatypes
                .get(d)
                .map(|dt| dt.value)
                .unwrap_or(Primitive::Float);
            let (ty, conv) = primitive_accessor(prim);
            let unit_doc = schema
                .datatypes
                .get(d)
                .map(|dt| {
                    let unit = dt.unit.as_deref().unwrap_or("none");
                    let mult = dt.multiplier.as_deref().unwrap_or("none");
                    if mult == "none" {
                        format!("    ///\n    /// Unit: `{unit}`.\n")
                    } else {
                        format!("    ///\n    /// Unit: `{unit}`, multiplier `{mult}`.\n")
                    }
                })
                .unwrap_or_default();
            if many {
                writeln!(
                    s,
                    "{doc}{unit_doc}    pub fn {method}(&self) -> impl Iterator<Item = {ty}> + '_ {{\n        self.0.get_all({path}).iter().filter_map(|s| s.value.{conv})\n    }}\n"
                )
                .unwrap();
            } else {
                writeln!(
                    s,
                    "{doc}{unit_doc}    #[inline]\n    pub fn {method}(&self) -> Option<{ty}> {{\n        self.0.get({path}).and_then(|v| v.{conv})\n    }}\n"
                )
                .unwrap();
            }
        }
        AttrKind::Enumeration(_) => {
            if many {
                writeln!(
                    s,
                    "{doc}    pub fn {method}(&self) -> impl Iterator<Item = EnumValueId> + '_ {{\n        self.0.get_all({path}).iter().filter_map(|s| s.value.as_enum())\n    }}\n"
                )
                .unwrap();
            } else {
                writeln!(
                    s,
                    "{doc}    #[inline]\n    pub fn {method}(&self) -> Option<EnumValueId> {{\n        self.0.get({path}).and_then(|v| v.as_enum())\n    }}\n"
                )
                .unwrap();
            }
        }
        AttrKind::Association { target, .. } => {
            let target_ty = rust_type(&target.local);
            if many {
                writeln!(
                    s,
                    "{doc}    pub fn {method}(&self) -> impl Iterator<Item = TypedRef<{target_ty}<'static>>> + '_ {{\n        self.0.get_all({path}).iter().filter_map(|s| s.value.as_reference()).map(|m| TypedRef::new(m.clone()))\n    }}\n"
                )
                .unwrap();
                // Resolving convenience that walks the dataset.
                writeln!(
                    s,
                    "    /// Resolve every `{}` through `dataset`, skipping unresolved references.\n    pub fn {method}_in<'d>(&self, dataset: &'d Dataset) -> impl Iterator<Item = {target_ty}<'d>> + 'd {{\n        let mrids: Vec<Mrid> = self.0.get_all({path}).iter().filter_map(|s| s.value.as_reference().cloned()).collect();\n        mrids.into_iter().filter_map(move |m| dataset.by_mrid(&m).map(|o| {target_ty}(o)))\n    }}\n",
                    attr.label
                )
                .unwrap();
            } else {
                writeln!(
                    s,
                    "{doc}    #[inline]\n    pub fn {method}(&self) -> Option<TypedRef<{target_ty}<'static>>> {{\n        self.0.get({path}).and_then(|v| v.as_reference()).map(|m| TypedRef::new(m.clone()))\n    }}\n"
                )
                .unwrap();
                writeln!(
                    s,
                    "    /// Resolve `{}` through `dataset`.\n    #[inline]\n    pub fn {method}_in<'d>(&self, dataset: &'d Dataset) -> Option<{target_ty}<'d>> {{\n        let m = self.0.get({path})?.as_reference()?;\n        dataset.by_mrid(m).map(|o| {target_ty}(o))\n    }}\n",
                    attr.label
                )
                .unwrap();
            }
        }
    }
}

fn primitive_accessor(p: Primitive) -> (&'static str, &'static str) {
    match p {
        Primitive::Boolean => ("bool", "as_bool()"),
        Primitive::Integer => ("i64", "as_i64()"),
        Primitive::Float | Primitive::Decimal => ("f64", "as_f64()"),
        _ => ("&str", "as_str()"),
    }
}

