//! Render the schema IR as Rust source.
//!
//! Output is committed to the repository rather than produced by a build script: builds
//! stay reproducible and fast for downstream users, docs.rs works, and a schema change
//! shows up as a reviewable diff.

use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use crate::ir::{AttrKind, Class, Multiplicity, Name, Primitive, Schema};

pub fn emit(schema: &Schema, out_dir: &Path, check: bool) -> Result<()> {
    let vintage_dir = out_dir.join(&schema.vintage);
    let files: Vec<(String, String)> = vec![
        ("mod.rs".to_owned(), emit_mod(schema)),
        ("tables.rs".to_owned(), emit_tables(schema)?),
        ("names.rs".to_owned(), emit_names(schema)),
        ("views.rs".to_owned(), emit_views(schema)),
    ]
    .into_iter()
    .map(|(name, src)| (name, rustfmt(&src)))
    .collect();

    if check {
        let mut stale = Vec::new();
        for (name, content) in &files {
            let path = vintage_dir.join(name);
            let current = std::fs::read_to_string(&path).unwrap_or_default();
            if normalize(&current) != normalize(content) {
                stale.push(path.display().to_string());
            }
        }
        let root = out_dir.join("mod.rs");
        let expected_root = rustfmt(&emit_root(schema));
        if normalize(&std::fs::read_to_string(&root).unwrap_or_default())
            != normalize(&expected_root)
        {
            stale.push(root.display().to_string());
        }
        if !stale.is_empty() {
            bail!(
                "generated sources are stale:\n  {}\nRun `cargo xtask codegen`.",
                stale.join("\n  ")
            );
        }
        println!("generated sources are up to date");
        return Ok(());
    }

    std::fs::create_dir_all(&vintage_dir)
        .with_context(|| format!("creating {}", vintage_dir.display()))?;
    for (name, content) in &files {
        let path = vintage_dir.join(name);
        std::fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
        println!("wrote {} ({} bytes)", path.display(), content.len());
    }
    let root = out_dir.join("mod.rs");
    std::fs::write(&root, rustfmt(&emit_root(schema)))?;
    println!("wrote {}", root.display());
    Ok(())
}

/// Ignore line-ending and trailing-whitespace differences when comparing.
fn normalize(s: &str) -> String {
    s.lines().map(str::trim_end).collect::<Vec<_>>().join("\n")
}

/// Format generated source with the workspace's rustfmt settings.
///
/// Generated code is committed and reviewed like any other source, so it is formatted
/// the same way. This also keeps `cargo fmt --check` and `cargo xtask codegen --check`
/// from contradicting each other in CI. If rustfmt is unavailable the unformatted source
/// is returned rather than failing the build.
fn rustfmt(src: &str) -> String {
    use std::io::Write as _;
    use std::process::{Command, Stdio};

    let spawned = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn();
    let Ok(mut child) = spawned else {
        eprintln!("warning: rustfmt not found; emitting unformatted source");
        return src.to_owned();
    };
    if let Some(mut stdin) = child.stdin.take() {
        // A broken pipe here means rustfmt rejected the input; the wait below reports it.
        let _ = stdin.write_all(src.as_bytes());
    }
    match child.wait_with_output() {
        Ok(out) if out.status.success() => {
            String::from_utf8(out.stdout).unwrap_or_else(|_| src.to_owned())
        }
        _ => {
            eprintln!("warning: rustfmt failed; emitting unformatted source");
            src.to_owned()
        }
    }
}

const HEADER: &str = "\
// @generated by `cargo xtask codegen` from the CIM/CGMES RDFS vocabularies.
// Do not edit by hand; edit the generator and regenerate.
//
// The RDFS vocabularies this file is derived from are published by ENTSO-E and the
// UCA International Users Group under the Apache License 2.0.
";

fn emit_root(schema: &Schema) -> String {
    let v = &schema.vintage;
    format!(
        "{HEADER}
//! Generated CIM schema vintages.

pub mod {v};
"
    )
}

fn emit_mod(schema: &Schema) -> String {
    let v = &schema.vintage;
    let title = match v.as_str() {
        "cgmes3" => "CGMES 3.0 (IEC TS 61970-600-1/-2:2021)",
        other => other,
    };
    format!(
        "{HEADER}
//! {title}.
//!
//! Generated from the ENTSO-E application profile vocabularies. [`SCHEMA`] is the entry
//! point; [`names`] gives compile-time constants for every class and attribute, and
//! [`views`] provides typed accessors.

mod tables;

pub mod names;
pub mod views;

pub use tables::SCHEMA;
pub use names::{{classes, attributes, enums, profiles}};
"
    )
}

