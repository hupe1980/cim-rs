fn emit_names(schema: &Schema) -> String {
    let mut s = String::with_capacity(1 << 20);
    s.push_str(HEADER);
    s.push_str(
        "
//! Compile-time identifiers for every schema element.
//!
//! Using these instead of string lookups makes model code both faster and
//! typo-proof: a renamed class becomes a compile error rather than a runtime `None`.

#![allow(non_upper_case_globals, non_snake_case)]

use crate::schema::{AttrId, ClassId, EnumId, EnumValueId, ProfileId};

/// Profiles of this vintage.
pub mod profiles {
    use super::ProfileId;
",
    );
    for (i, p) in schema.profiles.iter().enumerate() {
        let ident = rust_const(&p.keyword);
        writeln!(
            s,
            "    /// `{}` — {}\n    pub const {ident}: ProfileId = ProfileId({i});",
            p.keyword,
            escape_doc(&p.title)
        )
        .unwrap();
    }
    s.push_str("}\n\n/// Classes of this vintage.\npub mod classes {\n    use super::ClassId;\n");
    for (i, c) in schema.classes.values().enumerate() {
        let ident = rust_const(&c.name.local);
        writeln!(
            s,
            "    /// `{}`{}\n    pub const {ident}: ClassId = ClassId({i});",
            c.name.local,
            if c.concrete { "" } else { " (abstract)" }
        )
        .unwrap();
    }
    s.push_str("}\n\n");

    // Attributes are grouped per class so names stay unambiguous.
    s.push_str("/// Attributes, grouped by declaring class.\npub mod attributes {\n    use super::AttrId;\n");
    let mut rows: Vec<(&Name, usize)> = Vec::new();
    {
        let mut all: Vec<&Name> = Vec::new();
        for class in schema.classes.values() {
            for a in &class.attributes {
                all.push(&a.name);
            }
        }
        all.sort();
        for (i, n) in all.iter().enumerate() {
            rows.push((n, i));
        }
    }
    let mut by_class: BTreeMap<&str, Vec<(&Name, usize)>> = BTreeMap::new();
    for (name, id) in &rows {
        if let Some(owner) = name.owner() {
            by_class.entry(owner).or_default().push((name, *id));
        }
    }
    for (class, attrs) in by_class {
        let module = rust_module(class);
        writeln!(
            s,
            "    /// Attributes of `{class}`.\n    pub mod {module} {{\n        use super::AttrId;"
        )
        .unwrap();
        for (name, id) in attrs {
            let label = name.local.rsplit('.').next().unwrap_or("");
            writeln!(
                s,
                "        /// `{}`\n        pub const {}: AttrId = AttrId({id});",
                name.local,
                rust_const(label)
            )
            .unwrap();
        }
        s.push_str("    }\n");
    }
    s.push_str("}\n\n");

    // Enumerations and their literals.
    s.push_str("/// Enumerations and their literals.\npub mod enums {\n    use super::{EnumId, EnumValueId};\n");
    let mut value_id: BTreeMap<&Name, usize> = BTreeMap::new();
    {
        let mut all: Vec<&Name> = Vec::new();
        for e in schema.enums.values() {
            for v in &e.values {
                all.push(&v.name);
            }
        }
        all.sort();
        for (i, n) in all.iter().enumerate() {
            value_id.insert(n, i);
        }
    }
    for (ei, e) in schema.enums.values().enumerate() {
        let module = rust_module(&e.name.local);
        writeln!(
            s,
            "    /// `{}`\n    pub mod {module} {{\n        use super::{{EnumId, EnumValueId}};\n        /// The enumeration itself.\n        pub const TYPE: EnumId = EnumId({ei});",
            e.name.local
        )
        .unwrap();
        for v in &e.values {
            writeln!(
                s,
                "        /// `{}`\n        pub const {}: EnumValueId = EnumValueId({});",
                v.name.local,
                rust_const(&v.label),
                value_id[&v.name]
            )
            .unwrap();
        }
        s.push_str("    }\n");
    }
    s.push_str("}\n");
    s
}

